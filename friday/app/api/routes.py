"""REST API routes for Veritas AI — Antigravity Engine integration.

Key design:
- Pipeline singleton lives in `request.app.state.pipeline` (init'd via lifespan).
- /query and /verify-news use the JSON path (pipeline.run).
- /stream uses StreamingResponse + SSE (pipeline.stream_run) for <100ms TTFT.
"""
import asyncio
import logging
import time
from typing import Optional

from fastapi import APIRouter, Depends, HTTPException, Request
from fastapi.responses import JSONResponse, StreamingResponse

from app.core.config import settings
from app.core.cache import cache

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/api/v1")


# ---- Pipeline accessor ----

def _get_pipeline(request: Request):
    """Retrieve the singleton FridayPipeline from app.state."""
    pipeline = getattr(request.app.state, "pipeline", None)
    if pipeline is None:
        raise HTTPException(
            status_code=503,
            detail="Pipeline not initialized. Server is still starting up.",
        )
    return pipeline


# ---- Auth Helpers ----

def _require_api_key(request: Request) -> str:
    """Extract and validate API key from request headers."""
    api_key = request.headers.get("X-API-KEY")
    if not api_key:
        raise HTTPException(status_code=401, detail="API key required")

    from core.security import validate_api_key
    validate_api_key(api_key)
    return api_key


def _get_owner_email(api_key: str, request: Request) -> str:
    """Resolve owner email from API key, falling back to 'public'."""
    try:
        from core.security import get_current_user
        user = get_current_user(api_key, request)
        return user.get("owner", "public")
    except Exception:
        return "public"


# ---- Query Resolution ----

async def _resolve_query(request: Request, query: str, deep: bool = False, owner_email: str = "public") -> dict:
    """Run query through the singleton pipeline with caching."""
    # Check cache first
    cached = await cache.get(query)
    if cached is not None:
        cached["_cached"] = True
        return cached

    start = time.monotonic()
    pipeline = _get_pipeline(request)

    try:
        response = await pipeline.run(query)
    except Exception as e:
        logger.error(f"Pipeline error: {e}", exc_info=True)
        response = {"response": str(e), "error": True}

    response["latency_ms"] = round((time.monotonic() - start) * 1000, 1)

    # Cache result
    await cache.set(query, response)

    # Log to history (non-blocking)
    try:
        from core.history_store import log_query_result
        from models.schemas import QueryResponse

        payload = QueryResponse(
            response=response.get("response", ""),
            truth_score=response.get("truth_score"),
            sources=response.get("context_used", []),
        )
        asyncio.create_task(asyncio.to_thread(log_query_result, payload, owner_email))
    except Exception:
        pass

    return response


