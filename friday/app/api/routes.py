@router.post("/query")
async def query_endpoint(request: Request):
    """Direct query endpoint (no auth required). Returns complete JSON."""
    body = await request.json()
    query = body.get("query", "").strip()
    deep = body.get("deep", False)

    if not query:
        raise HTTPException(status_code=400, detail="Query is required")

    response = await _resolve_query(request, query, deep=deep)
    return response


@router.post("/verify-news")
async def verify_news(request: Request):
    """Public API for news verification (auth required)."""
    api_key = _require_api_key(request)
    owner_email = _get_owner_email(api_key, request)

    body = await request.json()
    query = body.get("claim", body.get("query", "")).strip()
    deep = body.get("deep", False)

    if not query:
        raise HTTPException(status_code=400, detail="Claim/query is required")

    response = await _resolve_query(request, query, deep=deep, owner_email=owner_email)
    return response


@router.post("/stream")
async def stream_query(request: Request):
    """
    Streaming query endpoint — Server-Sent Events.

    Returns tokens as they are generated by Ollama, achieving <100ms
    time-to-first-token. Truth Score and Hallucination Firewall results
    are appended as final SSE events after the LLM finishes.

    SSE event types:
      - meta:        {tier, model}
      - token:       {t: "..."}
      - truth_score: {truth_score: 0.85, breakdown: {...}}
      - done:        {response_length: 142}
    """
    body = await request.json()
    query = body.get("query", "").strip()

    if not query:
        raise HTTPException(status_code=400, detail="Query is required")

    pipeline = _get_pipeline(request)

    return StreamingResponse(
        pipeline.stream_run(query, voice_mode=bool(body.get("voice_mode", False))),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "Connection": "keep-alive",
            "X-Accel-Buffering": "no",  # Disable nginx buffering
        },
    )


@router.post("/voice/stream")
async def voice_stream_endpoint(request: Request):
    """
    Returns an audio/wav stream compatible with the existing Next.js frontend.
    TTFA < 200ms.
    """
    body = await request.json()
    text = body.get("text", "").strip()
    
    if not text:
        raise HTTPException(status_code=400, detail="Text is required for TTS")

    from app.voice.tts_service import tts_service
    
    return StreamingResponse(
        tts_service.stream_audio(text),
        media_type="audio/wav"
    )


@router.post("/stream-analysis")
async def stream_analysis(request: Request):
    """Get WebSocket stream authorization URL (auth required)."""
    api_key = _require_api_key(request)

    body = await request.json()
    query = body.get("query", "").strip()

    separator = "&" if "?" in settings.PUBLIC_WS_BASE_URL else "?"
    return {
        "status": "stream_authorized",
        "tunnel_socket_uri": f"{settings.PUBLIC_WS_BASE_URL}{separator}session_auth={api_key}",
        "query_linked": query,
    }


@router.get("/history")
async def get_history(request: Request, limit: int = 50):
    """Fetch query history."""
    api_key = request.headers.get("X-API-KEY")
    owner_email = _get_owner_email(api_key, request) if api_key else "public"

    try:
        from core.history_store import fetch_recent_history
        history = await asyncio.to_thread(fetch_recent_history, limit, owner_email)
        return {"history": history, "count": len(history)}
    except Exception as e:
        logger.error(f"History fetch failed: {e}")
        return {"history": [], "count": 0, "error": str(e)}


